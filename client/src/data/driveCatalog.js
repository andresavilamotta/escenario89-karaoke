// Permite alternar entre streaming directo desde Google Drive (usercontent) o a través del proxy Express local
// Por defecto se utiliza el proxy local (/api/videos/drive/:id) para máxima compatibilidad y soporte de Range Requests
export const USE_DIRECT_DRIVE_URL = false;

export const DRIVE_TRACKS = DRIVE_CATALOG_RAW.map((track) => ({
  ...track,
  videoUrl: USE_DIRECT_DRIVE_URL ? track.driveStreamUrl : track.proxyStreamUrl,
  badge: '☁️ Google Drive',
}));

// Mapa rápido por videoId para auto-intercepción
const DRIVE_TRACKS_BY_VIDEO_ID = new Map(
  DRIVE_TRACKS.map((t) => [t.videoId, t])
);

// Mapa rápido por driveFileId
const DRIVE_TRACKS_BY_FILE_ID = new Map(
  DRIVE_TRACKS.map((t) => [t.driveFileId, t])
);

/**
 * Busca canciones en el catálogo de Google Drive por término de búsqueda
 * @param {string} query
 * @returns {Array} canciones coincidentes
 */
export function searchDriveCatalog(query) {
  if (!query || typeof query !== 'string') return [];
  const clean = query.trim().toLowerCase();
  if (clean.length < 2) return [];

  const terms = clean.split(/\s+/).filter(Boolean);

  return DRIVE_TRACKS.filter((track) => {
    const targetText = `${track.title} ${track.author} ${track.videoId}`.toLowerCase();
    return terms.every((term) => targetText.includes(term));
  });
}

/**
 * Encuentra una canción de Google Drive por su videoId original de YouTube
 * @param {string} videoId
 * @returns {object|null}
 */
export function findDriveTrackByVideoId(videoId) {
  if (!videoId) return null;
  return DRIVE_TRACKS_BY_VIDEO_ID.get(videoId) || null;
}

/**
 * Encuentra una canción por su Drive File ID
 * @param {string} driveFileId
 * @returns {object|null}
 */
export function findDriveTrackByFileId(driveFileId) {
  if (!driveFileId) return null;
  return DRIVE_TRACKS_BY_FILE_ID.get(driveFileId) || null;
}
